/**
 * Merge and rollback — branch operations on the entry graph
 * (REFACTOR.md §K4, port of eta-agent's mergeBranch / rollback semantics,
 * storage and lane coupling stripped).
 *
 * Merging copies the side chain's entries (above the common ancestor) into the
 * target and appends one `merge` entry whose second parent is the side tip;
 * spliceMergedChain then makes every reader see the merged history identically.
 * Rollback moves the branch view back and keeps the discarded entries — the
 * history is not deleted, only unreachable from the new tip.
 */
import type { Usage } from "@earendil-works/pi-ai";
import type { MergeEntry, NewEntry } from "../types/entries";
import type { EntryGraph } from "./graph";

export interface MergeOptions {
	/** Short human/model-readable description of what was merged. */
	summary: string;
	usage?: Usage;
	/** Id for the merge entry; generated by the graph when omitted. */
	id?: string;
}

export interface MergeResult {
	entry: MergeEntry;
	/** Side-chain entries copied into the target, oldest first. */
	copiedIds: string[];
	/** Where the two branches last shared an entry, if they ever did. */
	commonAncestorId: string | null;
}

/** Merge `side` into `target`: copy the side chain, then append a merge entry. */
export function mergeBranch(target: EntryGraph, side: EntryGraph, options: MergeOptions): MergeResult {
	if (target === side) throw new Error("merge: a branch cannot merge into itself");
	const sideTipId = side.tipId();
	if (sideTipId === null) throw new Error("merge: source branch is empty");
	const sideTip = side.tip();
	if (sideTip === undefined) throw new Error(`merge: unknown source tip ${sideTipId}`);

	const targetChain = target.chain();
	const targetIds = new Set(targetChain.map((entry) => entry.id));
	// The merged branch view (spliced) is what counts as "already there": a side
	// tip reachable only through a previous merge entry must not be merged twice.
	const targetVisible = new Set(target.path().map((entry) => entry.id));
	if (targetIds.has(sideTipId)) {
		throw new Error("merge: branch is already part of this history");
	}
	if (targetVisible.has(sideTipId)) {
		throw new Error("merge: branch already merged");
	}

	const sideChain = side.chain();
	const commonAncestorId = sideChain.find((entry) => targetIds.has(entry.id))?.id ?? null;

	// Copy the side-only part, oldest first, so every parent lands before its child.
	// Walking root->tip, everything up to and including the common ancestor is
	// already shared and skipped; only what came after it gets copied.
	const copiedIds: string[] = [];
	const previousTip = target.tipId();
	let pastCommonAncestor = commonAncestorId === null;
	for (const entry of [...sideChain].reverse()) {
		if (!pastCommonAncestor) {
			if (entry.id === commonAncestorId) pastCommonAncestor = true;
			continue;
		}
		if (target.has(entry.id)) throw new Error(`merge: entry ${entry.id} already exists in the target branch`);
		target.append(entry as NewEntry);
		copiedIds.push(entry.id);
	}
	if (!pastCommonAncestor) throw new Error("merge: common ancestor is not an ancestor of the source tip");
	// The copies must not move the branch view; the merge entry does.
	target.setTip(previousTip);

	const entry = target.append({
		...(options.id === undefined ? {} : { id: options.id }),
		type: "merge",
		parentId: previousTip,
		mergedParentId: sideTipId,
		summary: options.summary,
		...(options.usage === undefined ? {} : { usage: options.usage }),
	} as NewEntry<MergeEntry>);

	return { entry, copiedIds, commonAncestorId };
}

/**
 * Merge a tip that is already in this graph.
 *
 * `mergeBranch` exists for the cross-journal case (adopting a fork's chain);
 * this is the same-journal one, where the side chain is already here and only
 * the merge entry is missing. The splice walks this graph for both parents, so
 * nothing needs copying — which is exactly why a session that keeps one journal
 * can merge a branch it wrote earlier.
 */
export function mergeTip(graph: EntryGraph, mergedTipId: string, options: MergeOptions): MergeEntry {
	if (!graph.has(mergedTipId)) throw new Error(`merge: entry ${mergedTipId} is not in this journal`);
	if (mergedTipId === graph.tipId()) throw new Error("merge: a branch cannot merge into itself");
	const visible = new Set(graph.path().map((entry) => entry.id));
	if (visible.has(mergedTipId)) throw new Error("merge: that branch is already part of this history");
	const parentId = graph.tipId();
	return graph.append({
		...(options.id === undefined ? {} : { id: options.id }),
		type: "merge",
		parentId,
		mergedParentId: mergedTipId,
		summary: options.summary,
		...(options.usage === undefined ? {} : { usage: options.usage }),
	} as NewEntry<MergeEntry>);
}

export type RollbackResult = { ok: true; entryId: string; droppedIds: string[] } | { ok: false; reason: string };

/**
 * Move the branch view back to `entryId`, keeping it. Everything after it
 * leaves the path but stays in the graph, so a later replay still sees it.
 */
export function rollback(graph: EntryGraph, entryId: string): RollbackResult {
	if (graph.byId(entryId) === undefined) return { ok: false, reason: `unknown entry ${entryId}` };
	if (!graph.chain().some((entry) => entry.id === entryId)) {
		return { ok: false, reason: `entry ${entryId} is not on the current branch` };
	}
	const before = new Set(graph.path().map((entry) => entry.id));
	graph.setTip(entryId);
	const after = new Set(graph.path().map((entry) => entry.id));
	const droppedIds = [...before].filter((id) => !after.has(id));
	return { ok: true, entryId, droppedIds };
}
