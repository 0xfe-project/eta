/**
 * Generate the entry a compiled host is built from: `apps/eta/scripts/build-host.ts` calls
 * `writeEmbedded` and compiles the `main.ts` it writes.
 *
 * Two modules, in `apps/eta/out/embed` (not in git, and nothing run from source reads them):
 * `embedded.ts` imports every file with `{ type: "file" }` and hands `resources.ts` the table of
 * original names; `main.ts` imports that, then the host. They are two because a module's body runs
 * after everything it imports: the table has to be in place before the host's modules run.
 *
 * What is embedded is named here, directory by directory, so nothing else on this computer can
 * end up in the executable; within them, dotfiles (a stray `.env`) stay out.
 */
import { createHash } from "node:crypto";
import {
  copyFileSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";

/** Past 9 the daemons shrink by a tenth at thirty times the time, for every `host:install`. */
const ZSTD_LEVEL = 9;

/** The directories whose files are unpacked; `resources.ts` names their directories by digest. */
const UNPACKED = ["cpa", "daemon"];

/** One embedded file: its name in the table, and the file to read at build time. */
export interface EmbeddedFile {
  name: string;
  path: string;
}

const isDotfile = (segment: string): boolean => segment.startsWith(".");

const byName = (a: EmbeddedFile, b: EmbeddedFile): number =>
  a.name < b.name ? -1 : a.name > b.name ? 1 : 0;

/** Every file in `dir`, named `<prefix>/<path inside it>`, dotfiles left out. */
export function filesIn(dir: string, prefix: string): EmbeddedFile[] {
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => join(entry.parentPath, entry.name))
    .filter((path) => !relative(dir, path).split(sep).some(isDotfile))
    .map((path) => ({
      name: `${prefix}/${relative(dir, path).split(sep).join("/")}`,
      path,
    }));
}

/** The hash of a directory's files, names and bytes: the name of its unpacked directory. */
export function digestOf(files: readonly EmbeddedFile[]): string {
  const hash = createHash("sha256");
  for (const { name, path } of [...files].sort(byName)) {
    hash.update(`${name}\0`);
    hash.update(readFileSync(path));
  }
  return hash.digest("hex").slice(0, 16);
}

/** The text of `embedded.ts`. */
export function embeddedModule(
  files: readonly EmbeddedFile[],
  digests: Readonly<Record<string, string>>,
  resources: string,
): string {
  const sorted = [...files].sort(byName);
  const lines = [
    "// Generated by apps/eta/scripts/embed.ts; only `bun build --compile` reads this.",
    `import { embedResources } from ${JSON.stringify(resources)};`,
    ...sorted.map(
      ({ path }, index) =>
        `import file${index} from ${JSON.stringify(path)} with { type: "file" };`,
    ),
    "",
    "embedResources({",
    "  files: {",
    ...sorted.map(
      ({ name }, index) => `    ${JSON.stringify(name)}: file${index},`,
    ),
    "  },",
    `  digests: ${JSON.stringify(digests)},`,
    "});",
    "",
  ];
  return lines.join("\n");
}

/** Each daemon build compressed into `out`, with the manifest as it was: it describes the builds. */
async function compressDaemons(
  daemons: string,
  out: string,
): Promise<EmbeddedFile[]> {
  mkdirSync(out, { recursive: true });
  const manifest = JSON.parse(
    readFileSync(join(daemons, "manifest.json"), "utf8"),
  ) as { builds: Record<string, { file: string }> };
  const copied = join(out, "manifest.json");
  copyFileSync(join(daemons, "manifest.json"), copied);
  const builds = await Promise.all(
    Object.values(manifest.builds).map(async ({ file }) => {
      const path = join(out, `${file}.zst`);
      writeFileSync(
        path,
        await Bun.zstdCompress(readFileSync(join(daemons, file)), {
          level: ZSTD_LEVEL,
        }),
      );
      return { name: `daemon/${file}.zst`, path };
    }),
  );
  return [{ name: "daemon/manifest.json", path: copied }, ...builds];
}

/** Write the two modules to `out`; returns the entry to compile. */
export async function writeEmbedded(options: {
  out: string;
  /** The built page, `apps/web/dist`. */
  web: string;
  /** The daemon builds and their manifest, `apps/daemon/out/dist`. */
  daemons: string;
  /** CLIProxyAPI for this platform, and `cpa-launcher` where there is one. */
  cpa: readonly string[];
}): Promise<string> {
  const { out } = options;
  const eta = resolve(import.meta.dirname, "..");
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });

  const cpa = options.cpa.map((path) => ({
    name: `cpa/${path.split(sep).at(-1) ?? path}`,
    path,
  }));
  const daemons = await compressDaemons(options.daemons, join(out, "daemon"));
  const files = [
    ...filesIn(join(eta, "src", "migrations"), "migrations"),
    {
      name: "Eta-Logo.png",
      path: resolve(eta, "..", "web", "public", "Eta-Logo.png"),
    },
    ...filesIn(options.web, "web"),
    ...cpa,
    ...daemons,
  ];
  const digests = Object.fromEntries(
    UNPACKED.map((dir) => [
      dir,
      digestOf(files.filter(({ name }) => name.startsWith(`${dir}/`))),
    ]),
  );

  const embedded = join(out, "embedded.ts");
  writeFileSync(
    embedded,
    embeddedModule(files, digests, join(eta, "src", "resources.ts")),
  );
  const entry = join(out, "main.ts");
  const shell = resolve(eta, "..", "daemon", "src", "windows-shell.ts");
  writeFileSync(
    entry,
    [
      "// Generated by apps/eta/scripts/embed.ts: the table first, then the host, unless this is",
      "// the process a Windows service runs, which loads none of it.",
      `import ${JSON.stringify(`./${relative(dirname(entry), embedded)}`)};`,
      'if (process.argv[2] === "service-run") {',
      `  const { runServiceShell } = await import(${JSON.stringify(shell)});`,
      "  runServiceShell(process.argv.slice(3));",
      "} else {",
      `  await import(${JSON.stringify(join(eta, "src", "main.ts"))});`,
      "}",
      "",
    ].join("\n"),
  );
  return entry;
}
