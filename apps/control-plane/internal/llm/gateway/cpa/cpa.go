// Package cpa embeds CLIProxyAPI (CPA) through its public SDK.
//
// Everything here uses exported SDK packages or CPA's HTTP management API;
// nothing reaches into CPA's internal packages. CPA keeps process-wide
// state (its logger, model registry, access providers and usage plugins),
// so a process builds one Proxy.
package cpa

