// Proxy is a configured, not yet running, CPA service.
type Proxy struct {
	Service *cliproxy.Service
	// Auths is the core auth manager the service routes with.
	Auths      *coreauth.Manager
	AuthDir    string
	ConfigPath string

	engine       atomic.Pointer[gin.Engine]
	ready        chan struct{}
	managementPW string
}

// New writes CPA's config into stateDir and builds the service; CPA's logs
// go to logger. CPA always listens itself: on a random loopback port that
// nothing routes to. Its routes are served through Handler, on the control
// plane's own listeners. Its management API takes a random per-process
// key (in the generated config, never the environment, which commands this
// process runs would inherit), from loopback callers only;
// Proxy.Management calls it in-process.
func New(stateDir string, logger *slog.Logger) (*Proxy, error) {
	authDir := filepath.Join(stateDir, "auths")
	if err := os.MkdirAll(authDir, 0o700); err != nil {
		return nil, err
	}
	// CPA wants a management key for any caller; this process's is random.
	pw := randomHex(24)
	cfgPath, err := WriteConfig(stateDir, pw)
	if err != nil {
		return nil, err
	}
	cfg, err := config.LoadConfig(cfgPath)
	if err != nil {
		return nil, fmt.Errorf("load CPA config: %w", err)
	}

	routeLogs(logger)
	// The only access provider: without one, CPA serves /v1 unauthenticated.
	sdkaccess.RegisterProvider(agentHeader{}.Identifier(), agentHeader{})

	store := sdkauth.GetTokenStore()
	if setter, ok := store.(interface{ SetBaseDir(string) }); ok {
		setter.SetBaseDir(authDir)
	}
	auths := coreauth.NewManager(store, nil, nil)

	p := &Proxy{Auths: auths, AuthDir: authDir, ConfigPath: cfgPath, ready: make(chan struct{}), managementPW: pw}
	svc, err := cliproxy.NewBuilder().
		WithConfig(cfg).
		WithConfigPath(cfgPath).
		WithCoreAuthManager(auths).
		WithServerOptions(
			sdkapi.WithRouterConfigurator(func(e *gin.Engine, _ *handlers.BaseAPIHandler, _ *config.Config) {
				p.engine.Store(e)
			}),
		).
		// Once its routes are all registered (gin's are not safe to add
		// while serving) and the credentials loaded.
		WithHooks(cliproxy.Hooks{OnAfterStart: func(*cliproxy.Service) { close(p.ready) }}).
		Build()
	if err != nil {
		return nil, err
	}
	p.Service = svc
	return p, nil
}

// WriteConfig generates CPA's config.yaml in stateDir, with managementKey
// and the API keys in providers.json, and returns its path.
func WriteConfig(stateDir, managementKey string) (string, error) {
	gemini, err := OpenProviders(stateDir).Gemini()
	if err != nil {
		return "", fmt.Errorf("read providers.json: %w", err)
	}
	raw, err := yaml.Marshal(map[string]any{
		"host":                     "127.0.0.1",
		"port":                     0,
		"auth-dir":                 filepath.Join(stateDir, "auths"),
		"debug":                    false,
		"logging-to-file":          false,
		"usage-statistics-enabled": false,
		"request-retry":            1,
		"remote-management": map[string]any{
			"allow-remote":          false,
			"secret-key":            managementKey,
			"disable-control-panel": true,
		},
		"gemini-api-key": GeminiConfig(gemini),
	})
	if err != nil {
		return "", err
	}
	cfgPath := filepath.Join(stateDir, "config.yaml")
	header := []byte("# Generated by the control plane on every start; edits are overwritten.\n")
	return cfgPath, os.WriteFile(cfgPath, append(header, raw...), 0o600)
}

// Run blocks until ctx is cancelled, then stops CPA's background work.
func (p *Proxy) Run(ctx context.Context) error { return p.Service.Run(ctx) }

// Ready is closed once CPA has loaded the credentials and serves.
func (p *Proxy) Ready() <-chan struct{} { return p.ready }

// serving is CPA's engine once Ready, else nil.
func (p *Proxy) serving() *gin.Engine {
	select {
	case <-p.ready:
		return p.engine.Load()
	default:
		return nil
	}
}

// Handler serves CPA's routes; 503 until Run has built them.
func (p *Proxy) Handler() http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		engine := p.serving()
		if engine == nil {
			w.Header().Set("Content-Type", "application/json")
			w.WriteHeader(http.StatusServiceUnavailable)
			_, _ = w.Write([]byte(`{"error":{"message":"the model service is starting","type":"server_error"}}`))
			return
		}
		engine.ServeHTTP(w, r)
	})
}

// Management returns a client for CPA's management API that dispatches
// in-process to the gin engine as a loopback caller.
func (p *Proxy) Management() *http.Client {
	return &http.Client{Transport: engineTransport{p}}
}

// ManagementURL builds a URL for Management().
func ManagementURL(path string) string { return "http://cpa.internal/v0/management" + path }

type engineTransport struct{ p *Proxy }

func (t engineTransport) RoundTrip(req *http.Request) (*http.Response, error) {
	engine := t.p.serving()
	if engine == nil {
		return nil, fmt.Errorf("CPA is not running yet")
	}
	r := req.Clone(req.Context())
	r.RemoteAddr = "127.0.0.1:1"
	r.RequestURI = r.URL.RequestURI()
	r.Header.Set("Authorization", "Bearer "+t.p.managementPW)
	if r.Body == nil {
		r.Body = http.NoBody
	}
	rec := httptest.NewRecorder()
	rec.Body = new(bytes.Buffer)
	engine.ServeHTTP(rec, r)
	res := rec.Result()
	res.Request = req
	return res, nil
}

// AgentHeader names the agent a /v1 request comes from. Only the runtime
// gateway and AXP's own services reach /v1 (the control plane's internal
// listener); the runtime gateway sets it after authenticating the runtime,
// replacing any the runtime sent.
const AgentHeader = "X-AXP-Agent-Id"

type agentHeader struct{}

func (agentHeader) Identifier() string { return "axp-agent" }

func (agentHeader) Authenticate(_ context.Context, r *http.Request) (*sdkaccess.Result, *sdkaccess.AuthError) {
	agent := r.Header.Get(AgentHeader)
	if agent == "" {
		return nil, sdkaccess.NewNoCredentialsError()
	}
	return &sdkaccess.Result{Provider: "axp-agent", Principal: agent}, nil
}

// routeLogs sends CPA's logs (logrus, which only CPA uses here) to logger
// as records, level and fields kept, rather than as text on a stream.
func routeLogs(logger *slog.Logger) {
	logrus.SetOutput(io.Discard)
	logrus.SetLevel(logrus.InfoLevel)
	logrus.StandardLogger().ReplaceHooks(logrus.LevelHooks{})
	logrus.AddHook(slogHook{logger.With("library", "cliproxy")})
}

type slogHook struct{ logger *slog.Logger }

func (slogHook) Levels() []logrus.Level { return logrus.AllLevels }

func (h slogHook) Fire(e *logrus.Entry) error {
	level := slog.LevelInfo
	switch {
	case e.Level <= logrus.ErrorLevel:
		level = slog.LevelError
	case e.Level == logrus.WarnLevel:
		level = slog.LevelWarn
	case e.Level >= logrus.DebugLevel:
		level = slog.LevelDebug
	}
	attrs := make([]slog.Attr, 0, len(e.Data))
	for k, v := range e.Data {
		attrs = append(attrs, slog.Any(k, v))
	}
	ctx := e.Context
	if ctx == nil {
		ctx = context.Background()
	}
	h.logger.LogAttrs(ctx, level, e.Message, attrs...)
	return nil
}

func randomHex(n int) string {
	b := make([]byte, n)
	_, _ = rand.Read(b)
	return hex.EncodeToString(b)
}
