-- +goose Up
-- Routines (docs/architecture/routines.md): each routine's versioned brief,
-- its runs and the user's feedback on them.

CREATE TABLE routine (
    id uuid PRIMARY KEY,
    name text NOT NULL,
    model text NOT NULL,
    schedule jsonb NOT NULL,
    timezone text NOT NULL,
    enabled boolean NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);

CREATE TABLE routine_run (
    id uuid PRIMARY KEY,
    routine_id uuid NOT NULL REFERENCES routine (id) ON DELETE CASCADE,
    status text NOT NULL CHECK (status IN ('running', 'sent', 'nothing_new', 'failed')),
    started_at timestamptz NOT NULL,
    finished_at timestamptz,
    report text,
    -- Written by the run for the next one.
    handoff text,
    error text
);

-- A routine runs once at a time.
CREATE UNIQUE INDEX routine_run_running ON routine_run (routine_id) WHERE status = 'running';
CREATE INDEX routine_run_started ON routine_run (routine_id, started_at DESC);

CREATE TABLE routine_feedback (
    id uuid PRIMARY KEY,
    run_id uuid NOT NULL REFERENCES routine_run (id) ON DELETE CASCADE,
    text text NOT NULL,
    created_at timestamptz NOT NULL,
    -- The revision could not be made; the brief stays as it was.
    revision_failed boolean NOT NULL DEFAULT false
);

CREATE TABLE routine_brief (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    routine_id uuid NOT NULL REFERENCES routine (id) ON DELETE CASCADE,
    version integer NOT NULL,
    text text NOT NULL,
    -- The feedback it was revised from; a brief keeps its text when that
    -- feedback goes.
    feedback_id uuid UNIQUE REFERENCES routine_feedback (id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL,
    UNIQUE (routine_id, version)
);
