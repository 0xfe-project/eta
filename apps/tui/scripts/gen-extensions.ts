/**
 * Write `src/extensions.gen.ts`: every feature module under `src/ext/`, imported and listed in
 * file name order. A feature is `src/ext/<name>.ts(x)` or `src/ext/<name>/index.ts(x)`.
 *
 *   bun scripts/gen-extensions.ts                 for this app
 *   bun scripts/gen-extensions.ts --root <dir>    for the app at <dir>
 */
import {
  existsSync,
  readdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { join, resolve } from "node:path";
import process from "node:process";

const MODULE_FILE = /^(?<name>[^.]+)\.tsx?$/;
const INDEX_FILES = ["index.ts", "index.tsx"];

/** The feature names under `extDir`, sorted. Throws when one name is both a file and a directory. */
export function findExtensionModules(extDir: string): string[] {
  if (!existsSync(extDir)) return [];
  const found = new Map<string, string[]>();
  for (const entry of readdirSync(extDir, { withFileTypes: true })) {
    let name: string | undefined;
    if (entry.isDirectory()) {
      if (
        INDEX_FILES.some((index) => existsSync(join(extDir, entry.name, index)))
      )
        name = entry.name;
    } else {
      name = MODULE_FILE.exec(entry.name)?.groups?.name;
    }
    if (name !== undefined)
      found.set(name, [...(found.get(name) ?? []), entry.name]);
  }
  const clashes = [...found].filter(([, entries]) => entries.length > 1);
  if (clashes.length > 0) {
    throw new Error(
      `One feature, two modules: ${clashes.map(([name, entries]) => `${name} (${entries.join(", ")})`).join("; ")}`,
    );
  }
  return [...found.keys()].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

export function renderExtensionsModule(names: readonly string[]): string {
  const imports = names.map(
    (name, i) => `import ext${i} from "./ext/${name}";`,
  );
  const list = names.map((_, i) => `ext${i}`).join(", ");
  return [
    "// Generated by scripts/gen-extensions.ts from the modules under src/ext/. Do not edit:",
    "// run `bun run --cwd apps/tui gen` after adding or removing a feature.",
    `import type { Extension } from "./extensions/types";`,
    ...imports,
    "",
    `export const extensions: Extension[] = [${list}];`,
    "",
  ].join("\n");
}

/**
 * Writes only when the content differs, and then whole: into a file beside it, renamed over it.
 * Tasks that run at the same time all start by generating this file, and a rewrite in place
 * truncates it first: another task reading it then would see it empty.
 */
function writeIfChanged(file: string, content: string): void {
  if (existsSync(file) && readFileSync(file, "utf8") === content) return;
  const next = `${file}.${process.pid}.tmp`;
  try {
    writeFileSync(next, content);
    renameSync(next, file);
  } catch (error) {
    rmSync(next, { force: true });
    throw error;
  }
}

function rootFromArgs(argv: readonly string[]): string {
  const at = argv.indexOf("--root");
  const given = at === -1 ? undefined : argv[at + 1];
  return given === undefined ? resolve(import.meta.dir, "..") : resolve(given);
}

if (import.meta.main) {
  const root = rootFromArgs(process.argv);
  try {
    const names = findExtensionModules(join(root, "src", "ext"));
    writeIfChanged(
      join(root, "src", "extensions.gen.ts"),
      renderExtensionsModule(names),
    );
  } catch (error) {
    process.stderr.write(
      `${error instanceof Error ? error.message : String(error)}\n`,
    );
    process.exit(1);
  }
}
