// Writes src/pages/templates/catalog.ts, the agent templates the client offers, from the role
// cards of unicodef1wn/grokbot-field-notes (MIT) at one pinned commit. Run it again with a new
// commit to take their changes: `bun run templates [--from <checkout>]`. What a card
// holds and what is kept of it: `parseRoleCard` (src/pages/templates/role-card.ts).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import process from "node:process";
import { parseRoleCard } from "../src/pages/templates/role-card";

const repo = "unicodef1wn/grokbot-field-notes";
const commit = "02780c04ef5f412b28573bce6f82afd15d195d1f";
const folder = "roster";
const out = resolve(
  import.meta.dir,
  "..",
  "src",
  "pages",
  "templates",
  "catalog.ts",
);

async function get(url: string, tries = 3): Promise<Response> {
  try {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${url}: ${response.status}`);
    return response;
  } catch (cause) {
    if (tries <= 1) throw cause;
    await Bun.sleep(1000);
    return get(url, tries - 1);
  }
}

async function cards(): Promise<[string, string][]> {
  const from = process.argv.indexOf("--from");
  if (from !== -1) {
    const dir = join(process.argv[from + 1]!, folder);
    return readdirSync(dir)
      .filter((name) => name.endsWith(".md") && name !== "README.md")
      .sort()
      .map((name) => [name, readFileSync(join(dir, name), "utf8")]);
  }
  const listing = (await get(
    `https://api.github.com/repos/${repo}/contents/${folder}?ref=${commit}`,
  ).then((response) => response.json())) as {
    name: string;
    download_url: string;
  }[];
  const files = listing
    .filter((file) => file.name.endsWith(".md") && file.name !== "README.md")
    .sort((a, b) => a.name.localeCompare(b.name));
  return Promise.all(
    files.map(
      async (file) =>
        [file.name, await (await get(file.download_url)).text()] as [
          string,
          string,
        ],
    ),
  );
}

if (import.meta.main) {
  const templates = (await cards()).map(([file, text]) =>
    parseRoleCard(file, text),
  );
  writeFileSync(
    out,
    `// Generated by scripts/agent-templates.ts: do not edit by hand.
// From https://github.com/${repo}/tree/${commit}/${folder}
// Copyright (c) 2026 unicodef1wn, MIT License (see THIRD_PARTY_NOTICES.md).
import type { AgentTemplate } from "./template";

export const templateSource = {
  repo: ${JSON.stringify(repo)},
  commit: ${JSON.stringify(commit)},
  url: ${JSON.stringify(`https://github.com/${repo}/tree/${commit}/${folder}`)},
  license: "MIT",
} as const;

export const templates: AgentTemplate[] = ${JSON.stringify(templates, null, 2)};
`,
  );
  console.log(`${templates.length} templates → ${out}`);
}
