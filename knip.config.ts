import type { KnipConfig } from "knip";

// Dead code check for the TypeScript workspaces (`bun run knip`). The Python
// and Go apps only use package.json for Turbo scripts.
export default {
  // System tools the Turbo scripts call.
  ignoreBinaries: ["go", "gofmt", "uv"],
  // scripts/dev.sh runs it by path.
  ignoreDependencies: ["concurrently"],
  // CSS files are part of the module graph: their @imports reference
  // packages (fonts, tw-animate-css, shadcn) and other stylesheets.
  compilers: {
    css: (text: string) =>
      [...text.matchAll(/@import\s+(?:url\()?["']([^"']+)["']/g)]
        .map(([, specifier]) => `import "${specifier}";`)
        .join("\n"),
  },
  workspaces: {
    "apps/web": {
      // routeTree.gen.ts only exists after a build, so the file routes are
      // entries themselves. public/sw.js is registered by URL in client.tsx.
      entry: ["src/routes/**/*.{ts,tsx}", "public/sw.js"],
      // Generated from the shadcn and brainless registries; unused exports
      // there are expected.
      ignore: ["src/components/ui/**", "src/components/brainless/**"],
      // Generated by the TanStack router plugin during dev and build.
      ignoreUnresolved: ["./routeTree.gen"],
    },
  },
} satisfies KnipConfig;
