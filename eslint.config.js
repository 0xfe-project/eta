import antfu from "@antfu/eslint-config";
import globals from "globals";

// The phone client (apps/mobile) is Native Shell: TSX compiled by nsh's own JSX
// compiler and run on QuickJS. Not React, not a browser, not Node.
const NSH = ["apps/mobile/**", "apps/client/**"];

// One config for the repository. Formatting belongs to dprint, so stylistic
// rules stay off; JSON is linted for validity and sorted package.json and
// tsconfig keys. Generated code is not linted.
export default antfu(
  {
    typescript: true,
    react: true,
    stylistic: false,
    jsonc: true,
    yaml: false,
    markdown: false,
    toml: false,
    ignores: [
      "**/*.gen.ts",
      // `.eta` is the session's own directory (memory, scratch copies of packages), not source.
      ".eta/**",
      "**/.venv/**",
      "**/out/**",
      // Test fixtures: written as plain JS for runtime evaluation.
      "**/test/**/fixtures/**",
      // Generated by nsh, and the Rust build of the phone app.
      "apps/mobile/.nsh/**",
      "apps/client/.nsh/**",
      "apps/mobile/native/target/**",
    ],
  },
  {
    // dprint's Biome plugin writes hex digits in lowercase (0xc0), and this
    // rule wants them uppercase (0xC0): the two fight on every save.
    rules: { "unicorn/number-literal-case": "off" },
  },
  {
    // The typescript-eslint based rule misreads plain JS scopes and reports
    // every variable as "only used as a type"; use the core rule there.
    files: ["**/*.js", "**/*.mjs"],
    rules: {
      "unused-imports/no-unused-vars": "off",
      "no-unused-vars": [
        "error",
        { argsIgnorePattern: "^_", varsIgnorePattern: "^_" },
      ],
    },
  },
  {
    // Programs, not modules: the entry points of the server and the host and
    // the Bun scripts that check a package's production imports. They await at
    // the top level and print to the terminal on purpose.
    files: [
      "packages/eta-server/src/main.ts",
      "apps/eta/src/main.ts",
      "packages/*/test/*.smoke.mjs",
    ],
    rules: { "antfu/no-top-level-await": "off", "no-console": "off" },
  },
  {
    files: ["packages/*/test/*.smoke.mjs"],
    languageOptions: { globals: globals.bunBuiltin },
  },
  {
    // The real-model smoke runs report what the model did on the terminal.
    files: [
      "packages/*/test/*.e2e.test.ts",
      "packages/eta-harness/src/testing/smoke-scenario.ts",
    ],
    rules: { "no-console": "off" },
  },
  {
    // A vertical scroll area is a SmoothScroll: it glides on the mouse wheel on
    // Windows and is a plain Scroll elsewhere. Only a horizontal one stays a Scroll.
    files: ["apps/client/src/**/*.tsx"],
    ignores: ["apps/client/src/components/smooth-scroll.tsx"],
    rules: {
      "no-restricted-syntax": [
        "error",
        {
          selector:
            "JSXOpeningElement[name.name='Scroll']:not(:has(JSXAttribute[name.name='horizontal']))",
          message:
            "Use SmoothScroll from components for a vertical scroll area; only a horizontal Scroll stays a Scroll.",
        },
      ],
    },
  },
  {
    // Native dialogs must go through NativeDialog / Modal so NotificationHost stays above
    // every dialog backdrop.
    files: ["apps/client/src/**/*.tsx"],
    ignores: ["apps/client/src/ui/dialog.tsx"],
    rules: {
      "no-restricted-imports": [
        "error",
        {
          paths: [
            {
              name: "nsh/base",
              importNames: ["Dialog"],
              message:
                "Use NativeDialog (or Modal) from ui/dialog so global notifications stay above dialog backdrops.",
            },
          ],
        },
      ],
    },
  },
)
  // nsh components run once and react through signals, so hooks order, the
  // `use` prefix, Fast Refresh and render purity do not apply to the phone app.
  .override("antfu/react/rules", { ignores: NSH })
  .append({
    // No DOM and no Node in the phone app: plain JavaScript globals only. Its
    // own globals and types come from nsh and are checked by `nsh check`.
    files: NSH,
    rules: { "unicorn/prefer-node-protocol": "off" },
    languageOptions: {
      globals: Object.fromEntries(
        Object.keys({ ...globals.browser, ...globals.node })
          .filter((name) => !(name in globals.es2021))
          .map((name) => [name, "off"]),
      ),
    },
  });
